CREATE TABLE IF NOT EXISTS txn_daily (
    event_id         TEXT,
    transaction_id   TEXT,
    user_id          TEXT,
    amount           DOUBLE PRECISION,
    currency         VARCHAR(3),
    segment           TEXT,
    transaction_type TEXT,
    direction        TEXT,
    sender_account   TEXT,
    receiver_account TEXT,
    merchant_id      TEXT,
    ip_address       INET,
    device_id        TEXT,
    device_type      TEXT,
    latitude         DOUBLE PRECISION,
    longitude        DOUBLE PRECISION,
    status           TEXT,
    event_timestamp  TIMESTAMP
);