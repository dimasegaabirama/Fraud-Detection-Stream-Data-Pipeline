CREATE TABLE transaction_events (
    event_id          VARCHAR(36)    PRIMARY KEY,
    transaction_id    VARCHAR(36)    NOT NULL,
    user_id           VARCHAR(36)    NOT NULL,
    amount            NUMERIC(18, 2) NOT NULL CHECK (amount > 0.00),
    currency          VARCHAR(3)     NOT NULL,
    segment           VARCHAR(20)    NOT NULL CHECK (segment IN ('retail', 'business', 'individual')),
    transaction_type  VARCHAR(20)    NOT NULL CHECK (transaction_type IN ('transfer', 'payment', 'cashout', 'top_up', 'withdrawal', 'refund')),
    direction         VARCHAR(10)    NOT NULL CHECK (direction IN ('in', 'out')),
    sender_account    VARCHAR(34),
    receiver_account  VARCHAR(34),
    merchant_id       VARCHAR(36),
    ip_address        VARCHAR(45)    NOT NULL,
    device_id         VARCHAR(36)    NOT NULL,
    device_type       VARCHAR(20)    NOT NULL CHECK (device_type IN ('ios', 'android', 'web')),
    latitude          VARCHAR(20)    NOT NULL,
    longitude         VARCHAR(20)    NOT NULL,
    status            VARCHAR(20)    NOT NULL CHECK (status IN ('success', 'failed', 'reserved')),
    event_timestamp   VARCHAR(30)    NOT NULL    -- ISO 8601 (UTC)
);