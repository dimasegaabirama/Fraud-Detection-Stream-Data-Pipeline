CREATE TABLE IF NOT EXISTS txn_raw (
    event_id VARCHAR,
    transaction_id VARCHAR,
    user_id VARCHAR,
    "timestamp" TIMESTAMP,
    amount DECIMAL,
    currency VARCHAR,
    status VARCHAR,
    transaction_type VARCHAR,
    direction VARCHAR,
    sender_account VARCHAR,
    receiver_account VARCHAR,
    merchant_id VARCHAR,
    ip_address VARCHAR,
    device_id VARCHAR,
    device_type VARCHAR,
    latitude DECIMAL,
    longitude DECIMAL
);
CREATE TABLE IF NOT EXISTS user_daily (
    event_date DATE,
    user_id VARCHAR,
    direction VARCHAR,
    txn_count INTEGER,
    amt_log_sum DECIMAL,
    amt_log_sum2 DECIMAL,
    active_flag INTEGER,
    velocity_sum DECIMAL,
    velocity_max DECIMAL,
    device_map JSONB,
    ip_map JSONB,
    first_seen_date DATE,
    last_seen_date DATE
);
CREATE TABLE IF NOT EXISTS user_baseline (
    user_id VARCHAR(255),
    segment VARCHAR(255),
    direction VARCHAR(255),
    n INTEGER,
    active_days INTEGER,
    amt_log_mean DECIMAL,
    amt_log_std DECIMAL,
    amt_low_threshold DECIMAL,
    amt_medium_threshold DECIMAL,
    amt_high_threshold DECIMAL,
    vel_p99 DECIMAL,
    vel_low_threshold DECIMAL,
    vel_medium_threshold DECIMAL,
    vel_high_threshold DECIMAL,
    dev_p99 DECIMAL,
    dev_low_threshold DECIMAL,
    dev_medium_threshold DECIMAL,
    dev_high_threshold DECIMAL,
    ip_p99 DECIMAL,
    ip_low_threshold DECIMAL,
    ip_medium_threshold DECIMAL,
    ip_high_threshold DECIMAL,
    device_map JSONB,
    ip_map JSONB,
    first_seen_date DATE,
    last_seen_date DATE,
    refreshed_at TIMESTAMP(3)
);

